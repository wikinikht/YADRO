"""
[server fork] tgws-server CLI.

Commands:
  gen      create a ready-to-run YAML config with generated secrets
  run      run proxy (+ SOCKS5 bridge) from a config
  links    print tg://proxy links and bot snippets for every secret
  secret   add/remove/list secrets in an existing config
  doctor   QUICK diagnostics: config, DNS, WS-gateway reachability, ports
  diagnose FULL diagnostic sweep (env/deps/config/crypto/network/e2e)
           with a "likely causes" section — run this when something
           does not work; supports --offline, --full, --json, --report
  systemd  print a ready systemd unit for this host
"""

import argparse
import getpass
import sys

from server import __version__
from server.config_loader import DEFAULT_CONFIG_PATH


def _cmd_gen(args) -> int:
    from server.generator import build_config_dict, write_config
    cfg = build_config_dict(
        n_secrets=args.secrets,
        port=args.port,
        host=args.host,
        fake_tls_domain=args.domain,
        socks5=not args.no_socks5,
        socks5_port=args.socks5_port,
        log_file=args.log_file,
    )
    try:
        write_config(args.out, cfg, force=args.force)
    except FileExistsError as exc:
        print(f'Error: {exc}', file=sys.stderr)
        return 1
    print(f'Config written: {args.out} (chmod 600)')
    print(f'Secrets: {args.secrets}, masking domain: '
          f'{args.domain or "(none, dd-secrets)"}')
    print()
    print('Next steps:')
    print(f'  1) tgws-server links -c {args.out}      # links + bot snippets')
    print(f'  2) tgws-server doctor -c {args.out}     # check this host')
    print(f'  3) tgws-server run -c {args.out}        # run in foreground')
    print('  4) tgws-server systemd                   # systemd unit to install')
    return 0


def _cmd_run(args) -> int:
    from server.runner import run_from_config
    return run_from_config(args.config, verbose=args.verbose)


def _cmd_links(args) -> int:
    from server.config_loader import load_config
    from server.generator import print_links
    cfg = load_config(args.config)
    print_links(cfg)
    return 0


def _cmd_secret(args) -> int:
    from server.config_loader import load_config
    from server.generator import add_secret, remove_secret, print_links
    if args.action == 'list':
        cfg = load_config(args.config)
        for i, s in enumerate(cfg['secrets']):
            mark = ' (primary)' if i == 0 else ''
            print(f'{s["name"]}: {s["value"][:8]}...{s["value"][-4:]}{mark}')
        return 0
    if args.action == 'add':
        if not args.name:
            print('Error: secret add requires NAME', file=sys.stderr)
            return 1
        created = add_secret(args.config, args.name)
        print(f"Secret '{created['name']}' added:")
        print(f"  value: {created['value']}")
        print(f'Now run: tgws-server links -c {args.config}')
        return 0
    if args.action == 'remove':
        if not args.name:
            print('Error: secret remove requires NAME', file=sys.stderr)
            return 1
        remove_secret(args.config, args.name)
        print(f"Secret '{args.name}' removed. Restart tgws-server to apply.")
        return 0
    return 1


def _cmd_doctor(args) -> int:
    from server.doctor import run_doctor
    return run_doctor(getattr(args, 'config', None) or None, args.config)


def _cmd_diagnose(args) -> int:
    from server.diagnostics import run_diagnose_cli
    return run_diagnose_cli(
        args.config,
        offline=args.offline,
        full=args.full,
        timeout=args.timeout,
        group=args.group,
        json_out=args.json_out,
        md_out=args.report,
    )


def _cmd_systemd(args) -> int:
    user = args.user or getpass.getuser()
    here = args.workdir
    unit = f"""\
# /etc/systemd/system/tgws-server.service
# tg-ws-proxy-server systemd unit (generated by tgws-server systemd)
[Unit]
Description=tg-ws-proxy-server (MTProto over WebSocket bridge)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User={user}
WorkingDirectory={here}
ExecStart={{sys.executable}} -m server.cli run -c {args.config}
Restart=always
RestartSec=3
# hardening
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths={here}
PrivateTmp=true
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
"""
    print(unit)
    print('# Install:')
    print(f'#   sudo cp tgws-server.service /etc/systemd/system/')
    print('#   sudo systemctl daemon-reload')
    print('#   sudo systemctl enable --now tgws-server')
    print('#   journalctl -u tgws-server -f')
    return 0


def build_parser() -> argparse.ArgumentParser:
    from server.diagnostics import GROUPS
    ap = argparse.ArgumentParser(
        prog='tgws-server',
        description='tg-ws-proxy-server: MTProto-over-WebSocket bridge '
                    'for Linux servers (fork of Flowseal/tg-ws-proxy)')
    ap.add_argument('--version', action='version',
                    version=f'tgws-server {__version__}')
    sub = ap.add_subparsers(dest='cmd', required=True)

    p = sub.add_parser('gen', help='generate a config with secrets')
    p.add_argument('-o', '--out', default=DEFAULT_CONFIG_PATH)
    p.add_argument('--secrets', type=int, default=2,
                   help='how many secrets to create (default 2)')
    p.add_argument('--port', type=int, default=1443)
    p.add_argument('--host', default='0.0.0.0')
    p.add_argument('--domain', default='',
                   help='FakeTLS masking domain (ee-secrets); '
                        'e.g. cloudflare.com. Empty = plain dd-secrets')
    p.add_argument('--no-socks5', action='store_true')
    p.add_argument('--socks5-port', type=int, default=1080)
    p.add_argument('--log-file', default='')
    p.add_argument('--force', action='store_true')
    p.set_defaults(fn=_cmd_gen)

    p = sub.add_parser('run', help='run the server from a config')
    p.add_argument('-c', '--config', default=DEFAULT_CONFIG_PATH)
    p.add_argument('-v', '--verbose', action='store_true')
    p.set_defaults(fn=_cmd_run)

    p = sub.add_parser('links', help='show tg:// links and bot snippets')
    p.add_argument('-c', '--config', default=DEFAULT_CONFIG_PATH)
    p.set_defaults(fn=_cmd_links)

    p = sub.add_parser('secret', help='add/remove/list secrets')
    p.add_argument('action', choices=['add', 'remove', 'list'])
    p.add_argument('name', nargs='?')
    p.add_argument('-c', '--config', default=DEFAULT_CONFIG_PATH)
    p.set_defaults(fn=_cmd_secret)

    p = sub.add_parser('doctor', help='quick diagnostics (config/DNS/WS/ports)')
    p.add_argument('-c', '--config', default=DEFAULT_CONFIG_PATH)
    p.set_defaults(fn=_cmd_doctor)

    p = sub.add_parser(
        'diagnose',
        help='full diagnostic sweep with likely-cause analysis '
             '(run this when something does not work)')
    p.add_argument('-c', '--config', default=DEFAULT_CONFIG_PATH)
    p.add_argument('--offline', action='store_true',
                   help='skip every network probe (sandboxed hosts / CI)')
    p.add_argument('--full', action='store_true',
                   help='also run live e2e: synthetic MTProto client through '
                        'the frontend and the SOCKS5 bridge (boots the stack '
                        'in-process if it is not running)')
    p.add_argument('--timeout', type=float, default=8.0,
                   help='per-network-check timeout, seconds (default 8)')
    p.add_argument('--group', choices=list(GROUPS), default=None,
                   help='run only one group (ENV/DEPS/CONFIG/CRYPTO/'
                        'NETWORK/SOCKS5/RUNTIME)')
    p.add_argument('--json', dest='json_out', metavar='PATH', default=None,
                   help='write a machine-readable JSON report')
    p.add_argument('--report', dest='report', metavar='PATH', default=None,
                   help='write a Markdown report (for issues/support)')
    p.set_defaults(fn=_cmd_diagnose)

    p = sub.add_parser('systemd', help='print a systemd unit')
    p.add_argument('-c', '--config', default=DEFAULT_CONFIG_PATH)
    p.add_argument('--user', default=None)
    p.add_argument('--workdir', default='{{WORKDIR}}')
    p.set_defaults(fn=_cmd_systemd)

    return ap


def main(argv=None) -> int:
    ap = build_parser()
    args = ap.parse_args(argv)
    if getattr(args, 'workdir', None) == '{{WORKDIR}}':
        import os
        args.workdir = os.path.abspath('.')
    if getattr(args, 'fn', None) is None:
        ap.print_help()
        return 2
    return args.fn(args)


if __name__ == '__main__':
    sys.exit(main())
